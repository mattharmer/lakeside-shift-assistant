#!/usr/bin/env node
/**
 * Concatenate the venue Markdown docs into worker/src/docs.js
 * so the Worker can ship them in the system prompt.
 *
 * Usage (from worker/): npm run build
 */
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const workerDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(workerDir, "..");
const docsDir = join(repoRoot, "docs");
const outDir = join(workerDir, "src");
const outFile = join(outDir, "docs.js");

function extractBoxedRules(md) {
  const match = md.match(/```[^\n]*\n([\s\S]*?)\n```/);
  if (!match) {
    throw new Error("Could not find the boxed custom instructions in docs/00-Custom-Instructions.md");
  }
  return match[1].trim();
}

const zeroMd = await readFile(join(docsDir, "00-Custom-Instructions.md"), "utf8");
const customInstructions = extractBoxedRules(zeroMd);

const files = (await readdir(docsDir))
  .filter((name) => /^\d{2}-.+\.md$/.test(name))
  .sort();

const venueParts = [];
for (const name of files) {
  const num = Number(name.slice(0, 2));
  if (num < 1 || num > 16) continue;
  const body = (await readFile(join(docsDir, name), "utf8")).trim();
  venueParts.push(`===== ${name} =====\n\n${body}`);
}

if (venueParts.length < 16) {
  throw new Error(`Expected documents 01–16; found ${venueParts.length}`);
}

const banner =
  "/* Generated by worker/build-docs.mjs — do not edit. From worker/: npm run build */\n";
const source =
  banner +
  `export const CUSTOM_INSTRUCTIONS = ${JSON.stringify(customInstructions)};\n` +
  `export const VENUE_DOCS = ${JSON.stringify(venueParts.join("\n\n"))};\n`;

await mkdir(outDir, { recursive: true });
await writeFile(outFile, source);
console.log(
  `Wrote ${outFile} (${source.length} chars, instructions + ${venueParts.length} documents)`
);
